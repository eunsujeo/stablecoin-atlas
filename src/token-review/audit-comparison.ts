import { isDeepStrictEqual } from 'node:util';
import { sha256 } from './input.js';
import type { CompilerInput } from './compiler.js';

export interface AuditSourceComparison {
  address: string; sourceMatch: 'MATCH' | 'MISMATCH'; settingsMatch: 'MATCH' | 'MISMATCH';
  files: { path: string; analyzedSha256: string | null; snapshotSha256: string | null;
    status: 'SAME' | 'DIFFERENT' | 'MISSING_IN_SNAPSHOT' | 'EXTRA_IN_SNAPSHOT' }[];
  analyzedInputEvidence: string; snapshotEvidence: string; evidenceRef: string;
  associationWithAudit: 'UNKNOWN';
}
export function compareAuditSources(analyzed: CompilerInput, snapshot: CompilerInput): Pick<AuditSourceComparison, 'sourceMatch' | 'settingsMatch' | 'files'> {
  const paths = [...new Set([...Object.keys(analyzed.sources), ...Object.keys(snapshot.sources)])].sort();
  const files: AuditSourceComparison['files'] = paths.map(path => {
    const a = Object.hasOwn(analyzed.sources, path) ? Buffer.from(analyzed.sources[path]!.content) : null;
    const b = Object.hasOwn(snapshot.sources, path) ? Buffer.from(snapshot.sources[path]!.content) : null;
    return { path, analyzedSha256: a ? sha256(a) : null, snapshotSha256: b ? sha256(b) : null,
      status: a === null ? 'EXTRA_IN_SNAPSHOT' : b === null ? 'MISSING_IN_SNAPSHOT' : a.equals(b) ? 'SAME' : 'DIFFERENT' };
  });
  // outputSelection is generated by the tool on both sides, not an audited build claim.
  return { sourceMatch: files.every(f => f.status === 'SAME') ? 'MATCH' : 'MISMATCH',
    settingsMatch: isDeepStrictEqual(analyzed.settings, snapshot.settings) ? 'MATCH' : 'MISMATCH', files };
}
